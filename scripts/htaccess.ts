/**
 * Apache configuration for shared hosting. The base path is baked in because
 * `ErrorDocument` needs a URL path, not a file path.
 */
export function renderHtaccess(basePath: string): string {
  const base = `/${basePath.replace(/^\/+|\/+$/g, '')}`.replace(/^\/$/, '');
  return `# Generated by scripts/write-htaccess.ts for base path "${base || '/'}". Do not edit.
Options -Indexes
DirectoryIndex index.html
ErrorDocument 404 ${base}/404.html

<IfModule mod_mime.c>
  AddType font/woff2 .woff2
  AddType image/svg+xml .svg
  AddType application/javascript .js
</IfModule>

<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set X-Frame-Options "DENY"
  Header always set Content-Security-Policy "frame-ancestors 'none'"

  # Hashed build output never changes under the same name; pages always revalidate.
  <If "%{REQUEST_URI} =~ m#/_astro/#">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </If>
  <FilesMatch "\\.html$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css application/javascript application/json image/svg+xml
</IfModule>
`;
}
