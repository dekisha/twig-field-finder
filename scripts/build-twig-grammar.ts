/**
 * Generate the Twig grammar used for highlighting:
 *
 * - `src/highlight/twig.tmLanguage.json`: Shiki's Twig grammar with the HTML
 *   rules and every embedded language (JS, CSS, SCSS, PHP, Python, Ruby and
 *   their transitive dependencies, ~2.3 MB) removed. Snippets in this app are
 *   pure Twig, so only the `twig-*` rules are needed. Readable and diffable.
 * - `src/highlight/twig.precompiled.ts`: the same grammar with every Oniguruma
 *   pattern compiled to a native JS RegExp literal, for Shiki's raw JavaScript
 *   engine. That engine skips the Oniguruma→JS conversion library entirely,
 *   which is most of the highlighter's client-side weight.
 *
 *   pnpm grammar:build
 *
 * Source grammar: https://github.com/shikijs/textmate-grammars-themes (MIT).
 */
import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import twigLangs from '@shikijs/langs/twig';
import { defaultJavaScriptRegexConstructor } from 'shiki/engine/javascript';

interface Rule {
  include?: string;
  patterns?: Rule[];
  [key: string]: unknown;
}

interface Grammar {
  name: string;
  scopeName: string;
  displayName?: string;
  patterns: Rule[];
  repository: Record<string, Rule>;
  [key: string]: unknown;
}

const TWIG_PREFIX = '#twig-';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outPath = join(root, 'src/highlight/twig.tmLanguage.json');
const precompiledPath = join(root, 'src/highlight/twig.precompiled.ts');

const source = twigLangs.find((l) => l.name === 'twig') as unknown as Grammar | undefined;
if (!source) throw new Error('Twig grammar not found in @shikijs/langs/twig');

/** Keep a rule only if everything it includes is a Twig rule. */
function prune(rules: Rule[]): Rule[] {
  return rules.flatMap((rule) => {
    if (rule.include !== undefined) return rule.include.startsWith(TWIG_PREFIX) ? [rule] : [];
    if (!rule.patterns) return [rule];
    const patterns = prune(rule.patterns);
    // A container whose children were all embedded-language rules is dropped.
    if (patterns.length === 0 && rule.patterns.length > 0) return [];
    return [{ ...rule, patterns }];
  });
}

const repository = Object.fromEntries(
  Object.entries(source.repository)
    .filter(([key]) => `#${key}`.startsWith(TWIG_PREFIX))
    .map(([key, rule]) => [
      key,
      { ...rule, ...(rule.patterns && { patterns: prune(rule.patterns) }) },
    ]),
);

const grammar = {
  $comment:
    'Generated by scripts/build-twig-grammar.ts from @shikijs/langs/twig (MIT). Twig rules only; do not edit.',
  name: 'twig',
  displayName: 'Twig',
  scopeName: source.scopeName,
  // Only the top-level includes of Twig rules survive (the rest is HTML).
  patterns: [...new Set(prune(source.patterns).flatMap((r) => r.include ?? []))].map((include) => ({
    include,
  })),
  repository,
};

// Every remaining include must resolve inside the trimmed grammar.
const unresolved = new Set<string>();
JSON.stringify(grammar, (key, value: unknown) => {
  if (key === 'include' && typeof value === 'string') {
    if (!value.startsWith('#') || !(value.slice(1) in repository)) unresolved.add(value);
  }
  return value;
});
if (unresolved.size > 0) {
  throw new Error(`Unresolved includes in trimmed grammar: ${[...unresolved].join(', ')}`);
}

await writeFile(outPath, `${JSON.stringify(grammar, null, 2)}\n`);
console.log(
  `Wrote ${outPath} (${Object.keys(repository).length} rules, ${JSON.stringify(grammar).length} bytes)`,
);

// Precompile: swap each pattern string for a marker, then splice in RegExp literals.
const PATTERN_KEYS = new Set(['match', 'begin', 'end', 'while']);
const literals: string[] = [];
const withMarkers = JSON.stringify(grammar, (key, value: unknown) => {
  if (!PATTERN_KEYS.has(key) || typeof value !== 'string') return value;
  // Same options Shiki uses at runtime, pinned to the ES2024 `v` flag.
  const regex = defaultJavaScriptRegexConstructor(value, { target: 'ES2024' });
  if (regex.constructor !== RegExp) {
    // Emulated patterns would need the oniguruma-to-es runtime on the client.
    throw new Error(`Pattern needs emulation, can't precompile natively: ${value}`);
  }
  literals.push(regex.toString());
  return `__REGEX_${String(literals.length - 1)}__`;
});
const body = withMarkers.replace(/"__REGEX_(\d+)__"/g, (_, i: string) => literals[Number(i)] ?? '');

await writeFile(
  precompiledPath,
  `// Generated by scripts/build-twig-grammar.ts from @shikijs/langs/twig (MIT). Do not edit.
import type { LanguageRegistration } from 'shiki/core';

const twig = Object.freeze(${body}) as unknown as LanguageRegistration;

export default twig;
`,
);
console.log(`Wrote ${precompiledPath} (${literals.length} native RegExp literals)`);
